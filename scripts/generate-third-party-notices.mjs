#!/usr/bin/env node
/**
 * Regenerates THIRD_PARTY_NOTICES.md from the actual production dependency
 * tree (`pnpm licenses list --prod --json`), reproducing each package's own
 * LICENSE text — MIT/ISC/BSD require the package's copyright line, not just
 * the generic license text, and the Vite-minified renderer bundles strip
 * header comments, so this file is the only attribution end users receive.
 *
 * Shipped with every build via electron-builder `extraResources` (see
 * apps/desktop/electron-builder.json) and opened from the About dialog.
 *
 * Usage: node scripts/generate-third-party-notices.mjs
 * (also exports collectPackages/ALLOWED_LICENSES for scripts/check-licenses.mjs)
 */
import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Licenses acceptable in the shipped app. Anything else (including "Unknown")
 * fails scripts/check-licenses.mjs in CI. Copyleft (GPL/AGPL/LGPL-static) is
 * deliberately absent. */
export const ALLOWED_LICENSES = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  'Python-2.0',
  'BlueOak-1.0.0',
  'Unlicense',
  'CC0-1.0',
  '0BSD',
  '(MPL-2.0 OR Apache-2.0)',
]);

/** Packages whose package.json misdeclares (or omits) the license field but
 * whose shipped license file was manually verified. Keep pinned to exact
 * versions so a bump forces re-verification. */
export const LICENSE_OVERRIDES = {
  'khroma@2.1.0': 'MIT', // no "license" field; shipped `license` file is standard MIT
};

/** Per-package remarks appended to the package's notice entry. */
const REMARKS = {
  dompurify:
    'DOMPurify is dual-licensed; Awakon uses it under the Apache License 2.0 option of its "(MPL-2.0 OR Apache-2.0)" license.',
  khroma:
    'khroma declares no `license` field in its package.json; the MIT license file shipped inside the package (reproduced below) applies.',
  katex:
    'The KaTeX fonts bundled with this application (KaTeX_*.woff2/.woff/.ttf) are distributed under the same MIT license.',
  'node-pty':
    'node-pty bundles winpty (MIT, © Ryan Prichard) and the ConPTY binaries conpty.dll / OpenConsole.exe from the Microsoft Terminal project (MIT, © Microsoft Corporation); their license files ship alongside the package.',
};

/** Runs `pnpm licenses list --prod --json` and flattens it to a sorted list of
 * unique { name, version, license, author, homepage, licenseText } entries. */
export function collectPackages() {
  // Static command string via the shell — pnpm is pnpm.cmd on Windows, which
  // Node refuses to spawn directly without shell since the DLL-hijack CVE fix.
  const raw = execSync('pnpm licenses list --prod --json', {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  const byLicense = JSON.parse(raw);
  const packages = [];
  for (const entries of Object.values(byLicense)) {
    for (const entry of entries) {
      // pnpm may aggregate several installed versions into one entry; emit one
      // notice per version so the override pinning stays exact.
      entry.versions.forEach((version, i) => {
        const license =
          LICENSE_OVERRIDES[`${entry.name}@${version}`] ?? entry.license;
        packages.push({
          name: entry.name,
          version,
          license,
          author: entry.author ?? null,
          homepage: entry.homepage ?? null,
          licenseText: readLicenseText(entry.paths[i] ?? entry.paths[0]),
        });
      });
    }
  }
  packages.sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
  return packages;
}

/** Finds and reads the license file inside a package directory. */
function readLicenseText(packageDir) {
  if (!packageDir) return null;
  let names;
  try {
    names = readdirSync(packageDir);
  } catch {
    return null;
  }
  const candidate = names
    .filter((n) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(n))
    // Prefer LICENSE over NOTICE, and bare names over qualified ones (.md/.txt fine).
    .sort(
      (a, b) =>
        Number(/^notice/i.test(a)) - Number(/^notice/i.test(b)) ||
        a.length - b.length,
    )[0];
  if (!candidate) return null;
  try {
    const text = readFileSync(join(packageDir, candidate), 'utf8').trim();
    return text.length > 0 ? text : null;
  } catch {
    return null;
  }
}

function renderNotices(packages) {
  const today = new Date().toISOString().slice(0, 10);
  const lines = [];
  lines.push('# Third-Party Notices');
  lines.push('');
  lines.push('<!-- Generated by scripts/generate-third-party-notices.mjs — do not edit by hand. -->');
  lines.push('');
  lines.push(
    `Awakon bundles the following third-party open-source software (production`,
    `dependency tree as of ${today}, ${packages.length} packages). Each package is the`,
    `copyright of its respective authors and is used under the license reproduced`,
    `with its entry below. Regenerate with \`pnpm notices\`.`,
  );
  lines.push('');
  lines.push('## Bundled runtime (Electron)');
  lines.push('');
  lines.push(
    'The packaged application embeds the Electron runtime (MIT), which itself',
    'bundles Chromium, V8, Node.js, and other components under a mix of',
    'permissive licenses, plus FFmpeg under LGPL-2.1 — distributed unmodified as',
    'a separate, dynamically linked library (`ffmpeg.dll` / `libffmpeg.so` /',
    '`libffmpeg.dylib`; sources available via https://github.com/electron/electron).',
    'The complete attribution for the Electron runtime ships with every build as',
    '`LICENSE.electron.txt` and `LICENSES.chromium.html` next to the executable.',
  );
  lines.push('');
  lines.push('## Installer (Windows NSIS builds only)');
  lines.push('');
  lines.push(
    'The Windows NSIS installer is produced with NSIS (zlib license,',
    'https://nsis.sourceforge.io/) and includes the `elevate.exe` helper from the',
    "electron-builder project's NSIS distribution",
    '(https://github.com/electron-userland/electron-builder-binaries). Neither is',
    'included in Microsoft Store (appx), macOS, or Linux builds.',
  );
  lines.push('');
  lines.push('## Package notices');
  lines.push('');
  for (const pkg of packages) {
    lines.push(`### ${pkg.name} ${pkg.version}`);
    lines.push('');
    const meta = [`License: ${pkg.license}`];
    if (pkg.author) meta.push(`Author: ${pkg.author}`);
    if (pkg.homepage) meta.push(`Homepage: ${pkg.homepage}`);
    lines.push(meta.join(' · '));
    lines.push('');
    const remark = REMARKS[pkg.name];
    if (remark) {
      lines.push(remark);
      lines.push('');
    }
    if (pkg.licenseText) {
      lines.push('```');
      lines.push(pkg.licenseText.replace(/```/g, "'''"));
      lines.push('```');
    } else {
      lines.push(
        `_No license file is shipped inside the package; the ${pkg.license}`,
        `license applies as declared in its package.json._`,
      );
    }
    lines.push('');
  }
  lines.push('## Trademarks');
  lines.push('');
  lines.push(
    '"Electron" is a trademark of the OpenJS Foundation. "Claude" and "Claude',
    'Code" are trademarks of Anthropic, PBC. "Codex" and references to other',
    'third-party AI tools are trademarks of their respective owners. References',
    'to these tools in this application are nominative — they describe',
    'compatibility and do not imply endorsement.',
  );
  lines.push('');
  return lines.join('\n');
}

function main() {
  const packages = collectPackages();
  const missing = packages.filter((p) => !p.licenseText && p.license === 'Unknown');
  if (missing.length > 0) {
    console.error(
      'Packages with neither a license file nor a declared license (add to LICENSE_OVERRIDES after manual verification):',
    );
    for (const p of missing) console.error(`  - ${p.name}@${p.version}`);
    process.exit(1);
  }
  const outPath = join(repoRoot, 'THIRD_PARTY_NOTICES.md');
  writeFileSync(outPath, renderNotices(packages));
  console.log(`Wrote ${outPath} (${packages.length} packages).`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
